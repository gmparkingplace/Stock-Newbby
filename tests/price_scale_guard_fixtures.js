'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),G=require('../results/dashboard/price-scale-guard');
const info=(min,max,above=0,below=0)=>({priceRange:{minValue:min,maxValue:max},margins:{above,below}});
assert.deepEqual(G.margins([],600),{top:.12,bottom:.25});
assert.equal(G.margins([info(-2,8)],600).bottom,.25,'음수 지표 자체를 자르지 않는다');
assert.equal(G.margins([info(.7,7.5,25,25)],600).bottom<.04,true);
assert.equal(G.margins([info(.741,11,50,50)],600).bottom,0,'마커 공간이 크면 불필요한 고정 여백만 없앤다');
assert.equal(G.margins([info(100,110)],600).bottom,.25);
const queue=[],listeners={},applied=[];
let opt={autoScale:true,invertScale:false,mode:0,scaleMargins:{top:.12,bottom:.25}};
const series={options:()=>({visible:true}),applyOptions:x=>{series.provider=x.autoscaleInfoProvider;},priceToCoordinate:p=>p===7.5?97:424};
const scale={options:()=>opt,getVisibleRange:()=>({from:.7,to:7.5}),applyOptions:x=>{applied.push(x);opt={...opt,...x};}};
const chart={priceScale:()=>scale,panes:()=>[{getHeight:()=>600}],timeScale:()=>({subscribeVisibleLogicalRangeChange:f=>listeners.range=f,subscribeSizeChange:f=>listeners.size=f})};
const guard=G.attach(chart,{clientHeight:600},()=>[series],fn=>queue.push(fn));
const raw=info(.7,7.5,25,25);assert.equal(series.provider(()=>raw),raw,'원래 자동축척 결과를 바꾸지 않는다');
while(queue.length)queue.shift()();
assert.equal(applied.length,1);assert(opt.scaleMargins.bottom<.04);assert(opt.autoScale);
opt.autoScale=false;guard.sync();while(queue.length)queue.shift()();assert.equal(applied.length,1,'수동 가격축을 덮지 않는다');
const html=fs.readFileSync(require('node:path').join(__dirname,'../results/dashboard/chart-first.html'),'utf8');
assert(html.includes('borderUpColor: UP, borderDownColor: DOWN'));
assert(html.includes('src="price-scale-guard.js"'));
console.log('저가 급락의 적응 여백·마커 보존·음수 지표·자동/수동축·캔들 테두리 검사 통과');
